  ORDER_DATE   DATE         NOT NULL COMMENT 'Date the order was placed',
  PRODUCT_ID   NUMBER(9,0)  NOT NULL COMMENT 'Foreign key to PRODUCTS.PRODUCT_ID',
  REGION       VARCHAR(20)  NOT NULL COMMENT 'Sales region: North, South, East or West',
  QUANTITY     NUMBER(9,0)  NOT NULL COMMENT 'Units sold on this order line',
