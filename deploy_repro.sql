INSERT INTO CHART_SUBAGENT_DEMO.DEMO.SALES
SELECT
  SEQ4() + 1                                                                AS ORDER_ID,
  DATEADD(day, -1 * UNIFORM(0, 364, RANDOM(11)), DATE '2026-09-14')         AS ORDER_DATE,
