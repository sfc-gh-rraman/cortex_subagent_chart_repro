/* ---------------------------------------------------------------------------
   STEP 2 - Two semantic views (Sales + Inventory), as in the report
   --------------------------------------------------------------------------- */
CREATE OR REPLACE SEMANTIC VIEW CHART_SUBAGENT_DEMO.DEMO.SALES_SV
  TABLES (
    SALES AS CHART_SUBAGENT_DEMO.DEMO.SALES
      PRIMARY KEY (ORDER_ID) COMMENT = 'One row per sales order line',
    PRODUCTS AS CHART_SUBAGENT_DEMO.DEMO.PRODUCTS
      PRIMARY KEY (PRODUCT_ID) COMMENT = 'Product master'
  )
  RELATIONSHIPS (
    SALES_TO_PRODUCTS AS SALES (PRODUCT_ID) REFERENCES PRODUCTS (PRODUCT_ID)
  )
  FACTS (
    SALES.UNITS AS QUANTITY COMMENT = 'Units sold on an order line',
    SALES.REVENUE_AMOUNT AS NET_REVENUE COMMENT = 'Net revenue of an order line in USD'
  )
  DIMENSIONS (
    SALES.ORDER_DATE AS ORDER_DATE
      WITH SYNONYMS = ('sale date','transaction date','date')
      COMMENT = 'Date the order was placed',
    SALES.ORDER_MONTH AS DATE_TRUNC('month', ORDER_DATE)
      WITH SYNONYMS = ('month','sales month')
      COMMENT = 'Calendar month of the order, truncated to the first day of the month',
    SALES.REGION AS REGION
      WITH SYNONYMS = ('sales region','territory','geo')
      COMMENT = 'Sales region: North, South, East or West',
    PRODUCTS.PRODUCT_NAME AS PRODUCT_NAME
      WITH SYNONYMS = ('product','item','sku name')
      COMMENT = 'Human readable product name',
    PRODUCTS.CATEGORY AS CATEGORY
      WITH SYNONYMS = ('product category','product family')
      COMMENT = 'Product category: Widgets, Gadgets or Accessories',
    PRODUCTS.LIST_PRICE AS UNIT_PRICE
      WITH SYNONYMS = ('unit price','price')
      COMMENT = 'List price per unit in USD'
  )
  METRICS (
    SALES.TOTAL_REVENUE AS SUM(SALES.REVENUE_AMOUNT)
      WITH SYNONYMS = ('revenue','sales','total sales','net revenue')
      COMMENT = 'Total net revenue in USD',
    SALES.TOTAL_UNITS AS SUM(SALES.UNITS)
      WITH SYNONYMS = ('units','units sold','volume','quantity')
      COMMENT = 'Total units sold',
    SALES.ORDER_COUNT AS COUNT(SALES.ORDER_ID)
      WITH SYNONYMS = ('orders','number of orders','order lines')
      COMMENT = 'Number of sales order lines',
    SALES.AVG_ORDER_REVENUE AS AVG(SALES.REVENUE_AMOUNT)
      WITH SYNONYMS = ('average order value','aov','average revenue per order')
      COMMENT = 'Average net revenue per order line in USD'
  )
  COMMENT = 'Sales analytics model: revenue, units and orders by product, category, region and month.';

CREATE OR REPLACE SEMANTIC VIEW CHART_SUBAGENT_DEMO.DEMO.INVENTORY_SV
  TABLES (
    INVENTORY AS CHART_SUBAGENT_DEMO.DEMO.INVENTORY
      PRIMARY KEY (SNAPSHOT_DATE, PRODUCT_ID, WAREHOUSE_CODE)
      COMMENT = 'One row per product per warehouse per snapshot date',
    PRODUCTS AS CHART_SUBAGENT_DEMO.DEMO.PRODUCTS
      PRIMARY KEY (PRODUCT_ID) COMMENT = 'Product master'
  )
  RELATIONSHIPS (
    INVENTORY_TO_PRODUCTS AS INVENTORY (PRODUCT_ID) REFERENCES PRODUCTS (PRODUCT_ID)
  )
  FACTS (
    INVENTORY.ON_HAND AS UNITS_ON_HAND COMMENT = 'Units physically on hand',
    INVENTORY.ON_ORDER AS UNITS_ON_ORDER COMMENT = 'Units on an open purchase order',
    INVENTORY.REORDER_LEVEL AS REORDER_POINT COMMENT = 'Reorder trigger level',
    INVENTORY.STOCK_VALUE_AMOUNT AS STOCK_VALUE COMMENT = 'Value of on-hand stock in USD at list price'
  )
  DIMENSIONS (
    INVENTORY.SNAPSHOT_DATE AS SNAPSHOT_DATE
      WITH SYNONYMS = ('as of date','inventory date')
      COMMENT = 'Date of the inventory snapshot',
    INVENTORY.WAREHOUSE_CODE AS WAREHOUSE_CODE
      WITH SYNONYMS = ('warehouse','dc','distribution center','location')
      COMMENT = 'Distribution center code holding the stock',
    PRODUCTS.PRODUCT_NAME AS PRODUCT_NAME
      WITH SYNONYMS = ('product','item','sku name')
      COMMENT = 'Human readable product name',
    PRODUCTS.CATEGORY AS CATEGORY
      WITH SYNONYMS = ('product category','product family')
      COMMENT = 'Product category: Widgets, Gadgets or Accessories'
  )
  METRICS (
    INVENTORY.TOTAL_ON_HAND AS SUM(INVENTORY.ON_HAND)
      WITH SYNONYMS = ('on hand','stock','units on hand','inventory level')
      COMMENT = 'Total units on hand',
    INVENTORY.TOTAL_ON_ORDER AS SUM(INVENTORY.ON_ORDER)
      WITH SYNONYMS = ('on order','incoming stock','open po units')
      COMMENT = 'Total units on open purchase orders',
    INVENTORY.TOTAL_STOCK_VALUE AS SUM(INVENTORY.STOCK_VALUE_AMOUNT)
      WITH SYNONYMS = ('stock value','inventory value')
      COMMENT = 'Total value of on-hand stock in USD',
    INVENTORY.AVG_REORDER_POINT AS AVG(INVENTORY.REORDER_LEVEL)
      WITH SYNONYMS = ('average reorder point')
      COMMENT = 'Average reorder trigger level'
  )
  COMMENT = 'Inventory analytics model: on-hand, on-order and stock value by product, category and warehouse.';


/* ---------------------------------------------------------------------------
   STEP 3 - SUBAGENT: owns both semantic views. Deliberately has NO chart tool.
   --------------------------------------------------------------------------- */
CREATE OR REPLACE AGENT SNOWFLAKE_INTELLIGENCE.AGENTS.DEMO_DATA_SUBAGENT
  COMMENT = 'Repro demo SUBAGENT: owns the Sales and Inventory semantic views and returns SQL result sets.'
  PROFILE = '{"display_name": "Demo Data Subagent (Sales + Inventory)", "color": "green"}'
  FROM SPECIFICATION
$$
models:
  orchestration: auto

orchestration:
  budget:
    seconds: 300
    tokens: 200000

instructions:
  response: |
    Return the full result set as a markdown table. Never truncate rows: if the query
    returns 5 rows, show all 5 rows. Do not summarise the data down to a sentence and
    do not editorialise - the caller needs the raw tabular data.
  orchestration: |
    You are a data retrieval subagent. You own two Cortex Analyst tools:
      - query_sales for anything about revenue, units sold, orders, products, categories, regions or sales months.
      - query_inventory for anything about units on hand, units on order, stock value, reorder points or warehouses.
    Always execute the generated SQL and return the actual rows.

tools:
  - tool_spec:
      type: cortex_analyst_text_to_sql
      name: query_sales
      description: |
        Queries the SALES_SV semantic view for sales performance.
        Metrics: total_revenue (USD), total_units, order_count, avg_order_revenue.
        Dimensions: product_name, category (Widgets/Gadgets/Accessories), region
        (North/South/East/West), order_date, order_month.
        Use for: revenue or unit rankings by product, category or region, and monthly trends.
        Do NOT use for stock levels or warehouse questions - use query_inventory instead.
  - tool_spec:
      type: cortex_analyst_text_to_sql
      name: query_inventory
      description: |
        Queries the INVENTORY_SV semantic view for the current inventory snapshot (2026-09-14).
        Metrics: total_on_hand, total_on_order, total_stock_value (USD), avg_reorder_point.
        Dimensions: product_name, category, warehouse_code (DC-CHICAGO/DC-DALLAS/DC-NEWARK/DC-RENO), snapshot_date.
        Use for: stock levels, stock value and replenishment questions by product, category or warehouse.
        Do NOT use for revenue or units sold - use query_sales instead.

tool_resources:
  query_sales:
    semantic_view: CHART_SUBAGENT_DEMO.DEMO.SALES_SV
    execution_environment:
      type: warehouse
      warehouse: COMPUTE_WH
      query_timeout: 120
  query_inventory:
    semantic_view: CHART_SUBAGENT_DEMO.DEMO.INVENTORY_SV
    execution_environment:
      type: warehouse
      warehouse: COMPUTE_WH
      query_timeout: 120
$$;


/* ---------------------------------------------------------------------------
   STEP 4 - MASTER AGENT: reaches the semantic views ONLY through the subagent,
            and owns data_to_chart.

   >>> THE CRITICAL BIT <<<
   The subagent is referenced with tool type `agent_toolset` and resource key
   `agent_name`. This is the only supported master->subagent mechanism.
   `type: agent` will be ACCEPTED by CREATE AGENT but FAILS at run time with
   "Tool type agent is not valid."
   --------------------------------------------------------------------------- */
CREATE OR REPLACE AGENT SNOWFLAKE_INTELLIGENCE.AGENTS.DEMO_MASTER_AGENT
  COMMENT = 'Repro demo MASTER agent: reaches the Sales/Inventory semantic views only through DEMO_DATA_SUBAGENT, and owns data_to_chart.'
  PROFILE = '{"display_name": "Demo Master Agent (charts via subagent)", "color": "blue"}'
  FROM SPECIFICATION
$$
models:
  orchestration: auto

orchestration:
  budget:
    seconds: 600
    tokens: 400000

instructions:
  response: |
    Present multi-row results as a table AND, when the result has more than 3 rows and
    contains at least one numeric measure, always render a chart with the data_to_chart tool.
    Always include units (USD, units).
  orchestration: |
    You are the master orchestrator. You do not own any semantic view directly.

    To obtain data, call the sales_inventory_data toolset, which reaches the Sales and
    Inventory analytics models. Pass the user's analytical question through in full.

    CHARTING RULE - this is mandatory:
    After you receive a result set, if it has MORE THAN 3 ROWS and includes at least one
    numeric column, you MUST call data_to_chart on that result set before writing your
    final answer. Choose the chart type that fits: bar for rankings and category
    comparisons, line for anything trended over time, pie only for share-of-total with
    fewer than 8 slices. Never describe a chart in text instead of calling data_to_chart.

tools:
  - tool_spec:
      type: agent_toolset
      name: sales_inventory_data
      description: |
        Retrieves sales and inventory result sets. Use for ANY question about revenue,
        units sold, orders, products, categories, regions, sales months, stock on hand,
        stock value, reorder points or warehouses. This is your only route to data.
  - tool_spec:
      type: data_to_chart
      name: data_to_chart
      description: |
        Renders a result set as an interactive chart. Call this whenever you have a
        result set with more than 3 rows and at least one numeric measure, including
        result sets that were retrieved through the sales_inventory_data toolset.

tool_resources:
  sales_inventory_data:
    agent_name: SNOWFLAKE_INTELLIGENCE.AGENTS.DEMO_DATA_SUBAGENT
$$;


/* ---------------------------------------------------------------------------
   STEP 5 - Verify
   --------------------------------------------------------------------------- */
DESCRIBE AGENT SNOWFLAKE_INTELLIGENCE.AGENTS.DEMO_MASTER_AGENT;

-- The exact question from the report. Returns 5 rows -> master agent calls
-- data_to_chart -> emits a response.chart event with a Vega-Lite v5 spec.
SELECT SNOWFLAKE.CORTEX.DATA_AGENT_RUN(
  'SNOWFLAKE_INTELLIGENCE.AGENTS.DEMO_MASTER_AGENT',
  '{"messages":[{"role":"user","content":[{"type":"text","text":"Show me sales by product for the top 5 products."}]}]}'
) AS MASTER_AGENT_RESPONSE;

