     "unable to render interactive charts when using a Master Agent-Subagent
      architecture ... data_to_chart on the Master Agent when it consumes data
      generated by the sql_execution tool running within a Subagent."

   Verified on account SFPSCOGS-RRAMAN_AWS_SI (Snowflake 10.32.102),
   2026-09-14. The master agent DOES invoke data_to_chart on subagent-sourced
